def tr(message, language=None):
    language = language or (session.get('language', 'en') if has_request_context() else 'en')
    return FR.get(message, message) if language == 'fr' else message


def money(value):
    return f'{value // 100}.{value % 100:02d}'


def install_i18n(app):
    app.jinja_env.globals['_'] = tr
    app.jinja_env.filters['money'] = money
